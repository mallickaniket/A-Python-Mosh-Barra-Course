import math     # This line imports the math module, which provides access to mathematical functions and constants.

x = 2.9
print(round(x))  # This will round the value of x to the nearest integer and print it to the console. In this case, it will print 3.
print(abs(-5))  # This will print the absolute value of -5 to the console, which is 5.
print(math.ceil(x))  # This will print the smallest integer greater than or equal to x to the console. In this case, it will print 3.
print(math.floor(x))  # This will print the largest integer less than or equal to x to the console. In this case, it will print 2.